export type StringKey = keyof (typeof strings)['bn'];

/** Looks up a string and fills `{name}` placeholders. Unknown placeholders are left as they are. */
export function t(key: StringKey, lang: Lang = 'bn', vars?: Record<string, string | number>): string {
  const text: string = strings[lang][key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
