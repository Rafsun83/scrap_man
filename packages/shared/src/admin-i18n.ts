export type AdminStringKey = keyof (typeof adminStrings)['en'];

/** Looks up an admin string and fills `{name}` placeholders. Unknown placeholders are left as they are. */
export function ta(key: AdminStringKey, lang: Lang = 'en', vars?: Record<string, string | number>): string {
  const text: string = adminStrings[lang][key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
